#include "session_json.h"

#include <stdlib.h>
#include <string.h>

#include "cJSON.h"

static cJSON *str_or_null(const char *s)
{
    return s ? cJSON_CreateString(s) : cJSON_CreateNull();
}

char *sc_session_json_build(const sc_session_opts_t *o)
{
    if (!o || !o->voice_session_id || !*o->voice_session_id) return NULL;
    const char *voice = o->voice ? o->voice : "juniper";
    size_t vlen = strlen(voice);
    if (vlen == 0 || vlen > 64) return NULL;
    if (o->language && (!*o->language || strlen(o->language) > 64)) return NULL;
    if (o->timezone_offset_min > 1440 || o->timezone_offset_min < -1440) return NULL;

    cJSON *s = cJSON_CreateObject();
    if (!s) return NULL;
    cJSON_AddItemToObject(s, "conversation_id", str_or_null(o->conversation_id));
    cJSON_AddItemToObject(s, "language_code", str_or_null(o->language));
    cJSON_AddStringToObject(s, "requested_default_model", "");
    cJSON_AddStringToObject(s, "voice", voice);
    cJSON_AddStringToObject(s, "voice_session_id", o->voice_session_id);
    cJSON_AddStringToObject(s, "voice_status_request_id", o->voice_session_id);
    cJSON_AddNumberToObject(s, "timezone_offset_min", o->timezone_offset_min);
    cJSON_AddStringToObject(s, "timezone", o->timezone ? o->timezone : "UTC");
    cJSON_AddStringToObject(s, "voice_mode", "wingman");
    cJSON_AddStringToObject(s, "model_slug", "");
    cJSON_AddItemToObject(s, "client_tools", cJSON_CreateArray());
    cJSON_AddBoolToObject(s, "history_and_training_disabled", 0);
    cJSON *mode = cJSON_AddObjectToObject(s, "conversation_mode");
    if (mode) cJSON_AddStringToObject(mode, "kind", "primary_assistant");
    cJSON_AddStringToObject(s, "model_slug_advanced", "");
    cJSON_AddBoolToObject(s, "enable_message_streaming", 1);
    cJSON_AddStringToObject(s, "backend_reasoning_effort", "high");
    cJSON_AddStringToObject(s, "chat_mode", "chat");

    if (o->overrides_json) {
        cJSON *ov = cJSON_Parse(o->overrides_json);
        if (cJSON_IsObject(ov)) {
            cJSON *it = ov->child;
            while (it) {
                cJSON *next = it->next;
                if (!strcmp(it->string, "voice_session_id") || !strcmp(it->string, "voice_status_request_id")) {
                    it = next; /* per-call ids are always generated by the device */
                    continue;
                }
                cJSON *item = cJSON_DetachItemViaPointer(ov, it);
                /* item->string still holds the key; replace via pointer so cJSON
                 * never frees the key it is about to copy. */
                cJSON *existing = cJSON_GetObjectItemCaseSensitive(s, item->string);
                if (existing) {
                    cJSON_ReplaceItemViaPointer(s, existing, item);
                } else {
                    item->next = item->prev = NULL;
                    cJSON_AddItemToArray(s, item); /* keeps item->string as the key */
                }
                it = next;
            }
        }
        cJSON_Delete(ov);
    }
    char *out = cJSON_PrintUnformatted(s);
    cJSON_Delete(s);
    return out;
}
